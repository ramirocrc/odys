"""Generate the brand stylesheet from the brand tokens.

Usage:
    uv run --locked python docs/generate_brand.py

Output:
    Writes docs/assets/stylesheets/brand.css (git-ignored build output) from
    docs/brand/tokens.json, the single source of truth for Odys colours and fonts.
    The stylesheet loads the brand fonts, exposes every colour as ``--odys-<name>``
    and maps zensical's ``--md-*`` theme variables to the brand in both colour
    schemes. The landing page (home.css, home.js) and the docs build on it.
"""

import json
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote_plus

DOCS_DIR = Path(__file__).parent
TOKENS_PATH = DOCS_DIR / "brand" / "tokens.json"
OUTPUT_PATH = DOCS_DIR / "assets" / "stylesheets" / "brand.css"

# zensical theme variable -> semantic scheme role in tokens.json. Link hover uses the accent.
THEME_VARIABLES = {
    "--md-default-bg-color": "background",
    "--md-default-fg-color": "foreground",
    "--md-default-fg-color--light": "foreground-muted",
    "--md-primary-fg-color": "header",
    "--md-primary-fg-color--light": "header",
    "--md-primary-fg-color--dark": "header",
    "--md-primary-bg-color": "header-text",
    "--md-accent-fg-color": "accent",
    "--md-typeset-a-color": "link",
    "--md-code-bg-color": "code-background",
    "--md-code-fg-color": "code-foreground",
}
SCHEME_SELECTORS = {"light": '[data-md-color-scheme="default"]', "dark": '[data-md-color-scheme="slate"]'}


@dataclass(frozen=True)
class Font:
    """A brand font role: Google Fonts family, CSS fallback stack and the styles to load.

    A role with ``widths`` loads the family's variable width axis over that range, with its
    weights as a continuous range too, so display headings can widen with ``font-stretch``.
    """

    family: str
    fallback: str
    weights: tuple[int, ...] = (400,)
    widths: tuple[int, ...] = ()
    italic: bool = False

    @property
    def stack(self) -> str:
        """CSS font-family value."""
        return f'"{self.family}", {self.fallback}'

    @property
    def google_fonts_query(self) -> str:
        """The ``family=`` parameter of a Google Fonts css2 URL."""
        name = quote_plus(self.family)
        if self.italic:
            return f"family={name}:ital@1"
        if self.widths:
            widths = f"{min(self.widths)}..{max(self.widths)}"
            return f"family={name}:wdth,wght@{widths},{min(self.weights)}..{max(self.weights)}"
        return f"family={name}:wght@{';'.join(str(w) for w in self.weights)}"


@dataclass(frozen=True)
class Brand:
    """Parsed brand tokens."""

    colors: dict[str, str]
    schemes: dict[str, dict[str, str]]
    fonts: dict[str, Font]


def load_brand(path: Path = TOKENS_PATH) -> Brand:
    """Parse the brand tokens file."""
    raw = json.loads(path.read_text())
    fonts = {
        role: Font(
            family=spec["family"],
            fallback=spec["fallback"],
            weights=tuple(spec.get("weights", (400,))),
            widths=tuple(spec.get("widths", ())),
            italic=bool(spec.get("italic", False)),
        )
        for role, spec in raw["font"].items()
    }
    return Brand(colors=dict(raw["color"]), schemes=dict(raw["scheme"]), fonts=fonts)


def _block(selector: str, declarations: dict[str, str]) -> str:
    body = "\n".join(f"  {name}: {value};" for name, value in declarations.items())
    return f"{selector} {{\n{body}\n}}"


def render_brand_css(brand: Brand) -> str:
    """Render brand.css from the brand tokens."""
    root = {f"--odys-{name}": value for name, value in brand.colors.items()}
    root.update({f"--odys-font-{role}": font.stack for role, font in brand.fonts.items()})
    root["--md-text-font"] = f'"{brand.fonts["sans"].family}"'
    root["--md-code-font"] = f'"{brand.fonts["mono"].family}"'
    query = "&".join(font.google_fonts_query for font in brand.fonts.values())

    blocks = [
        "/* Generated by docs/generate_brand.py from docs/brand/tokens.json. Do not edit by hand. */",
        f'@import url("https://fonts.googleapis.com/css2?{query}&display=swap");',
        _block(":root", root),
    ]
    for scheme, selector in SCHEME_SELECTORS.items():
        roles = brand.schemes[scheme]
        theme = {variable: f"var(--odys-{roles[role]})" for variable, role in THEME_VARIABLES.items()}
        accent = f"var(--odys-{roles['accent']})"
        theme["--md-accent-fg-color--transparent"] = f"color-mix(in srgb, {accent} 10%, transparent)"
        # The header is drawn with this translucent background; keep it the brand background.
        background = f"var(--odys-{roles['background']})"
        theme["--md-default-bg-color--light"] = f"color-mix(in srgb, {background} 54%, transparent)"
        blocks.append(_block(selector, theme))
    return "\n\n".join(blocks) + "\n"


def generate_brand_css() -> None:
    """Write brand.css from the brand tokens."""
    OUTPUT_PATH.write_text(render_brand_css(load_brand()))
    print(f"  ✓ {OUTPUT_PATH.relative_to(DOCS_DIR)}")


if __name__ == "__main__":
    print("Generating brand stylesheet...")
    generate_brand_css()
    print("Done!")
