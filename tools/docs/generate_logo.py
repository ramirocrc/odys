"""Generate the Odys logo SVGs from the Michroma font.

Usage:
    uv run --locked python tools/docs/generate_logo.py

Output:
    Writes docs/assets/brand/: the "Odys" wordmark and the standalone O for dark and light
    backgrounds, and a transparent favicon for dark and light browser themes (overrides/main.html
    picks one). The letters are Michroma's own outlines (tools/docs/brand/fonts/, SIL Open Font
    License 1.1). The O has its top-right corner cut away, the top stroke with a vertical cut
    and the right stroke with a horizontal one, and a dot on the stroke at the corner. Colours
    come from tools/docs/brand/tokens.json.

    The SVGs are committed because the README links them, so rerun this after changing the font,
    the cut or the colours; tests/docs/test_logo_assets.py fails while they are out of date.
"""

import itertools
import json
import math
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import NamedTuple

import pathops
from fontTools.pens.basePen import BasePen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from typing_extensions import override

TOOLS_DIR = Path(__file__).parent
REPOSITORY_ROOT = TOOLS_DIR.parent.parent
FONT_PATH = TOOLS_DIR / "brand" / "fonts" / "Michroma-Regular.ttf"
TOKENS_PATH = TOOLS_DIR / "brand" / "tokens.json"
OUTPUT_DIR = REPOSITORY_ROOT / "docs" / "assets" / "brand"

WORD = "Odys"
BASELINE = 1600
CURVE_STEPS = 32
FAR = 10_000.0

CORNER_PIVOT_X = 1274.0
CORNER_PIVOT_Y = 788.0
CORNER_CUT = 220.0
DOT_ANGLE = math.radians(45)
DOT_RADIUS = 0.6 * 192

WORDMARK_HEIGHT = 100
MARK_HEIGHT = 100
FAVICON_SIZE = 64
FAVICON_PADDING = 0.02
FAVICON_EMBOLDEN = 90.0
FAVICON_DOT_SCALE = 1.35

NOTICE = (
    "<!-- Generated by tools/docs/generate_logo.py. Letterforms from Michroma "
    "(Copyright 2011 The Michroma Project Authors), SIL Open Font License 1.1. -->"
)


class Point(NamedTuple):
    """A point in font units."""

    x: float
    y: float


class ViewBox(NamedTuple):
    """An SVG viewBox."""

    x: float
    y: float
    width: float
    height: float

    @classmethod
    def around(cls, bounds: tuple[float, float, float, float]) -> "ViewBox":
        """The smallest whole-unit viewBox containing the bounds (x_min, y_min, x_max, y_max)."""
        x_min, y_min = math.floor(bounds[0]), math.floor(bounds[1])
        return cls(x_min, y_min, math.ceil(bounds[2]) - x_min, math.ceil(bounds[3]) - y_min)

    def __str__(self) -> str:
        """The viewBox attribute value."""
        return " ".join(_number(value) for value in self)


@dataclass(frozen=True)
class Palette:
    """The colours of the letters and of the dot on one background."""

    letters: str
    dot: str


@dataclass(frozen=True)
class LogoOutlines:
    """The logo's shapes in SVG coordinates (font units, y down, baseline at BASELINE)."""

    ring: pathops.Path
    letters: pathops.Path
    dot_centre: Point


class ContourFlattener(BasePen):
    """Collects each contour of a glyph as a polyline in font units (y up)."""

    def __init__(self) -> None:
        """Start with no contours."""
        super().__init__(glyphSet=None)
        self.contours: list[list[Point]] = []

    @override
    def _moveTo(self, pt: tuple[float, float]) -> None:
        self.contours.append([Point(*pt)])

    @override
    def _lineTo(self, pt: tuple[float, float]) -> None:
        self.contours[-1].append(Point(*pt))

    @override
    def _curveToOne(self, pt1: tuple[float, float], pt2: tuple[float, float], pt3: tuple[float, float]) -> None:
        controls = (self.contours[-1][-1], Point(*pt1), Point(*pt2), Point(*pt3))
        self.contours[-1].extend(_cubic_point(controls, step / CURVE_STEPS) for step in range(1, CURVE_STEPS + 1))

    @override
    def _closePath(self) -> None:
        self.contours[-1].append(self.contours[-1][0])


def _cubic_point(controls: tuple[Point, Point, Point, Point], t: float) -> Point:
    weights = ((1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t**2, t**3)
    return Point(
        sum(w * p.x for w, p in zip(weights, controls, strict=True)),
        sum(w * p.y for w, p in zip(weights, controls, strict=True)),
    )


def _number(value: float) -> str:
    return f"{value:.1f}".rstrip("0").rstrip(".")


def _glyph_name(font: TTFont, char: str) -> str:
    character_map = font.getBestCmap()
    if character_map is None:
        msg = f"{FONT_PATH.name} has no Unicode character map"
        raise LookupError(msg)
    return character_map[ord(char)]


def _glyph_outline(font: TTFont, char: str, x_offset: float) -> pathops.Path:
    path = pathops.Path()
    pen = TransformPen(path.getPen(), (1, 0, 0, -1, x_offset, BASELINE))
    font.getGlyphSet()[_glyph_name(font, char)].draw(pen)
    return path


def _ray_hit(start: Point, end: Point, origin: Point, direction: Point) -> float | None:
    edge = Point(end.x - start.x, end.y - start.y)
    denominator = direction.x * edge.y - direction.y * edge.x
    if math.isclose(denominator, 0):
        return None
    offset = Point(start.x - origin.x, start.y - origin.y)
    distance = (offset.x * edge.y - offset.y * edge.x) / denominator
    along_edge = (offset.x * direction.y - offset.y * direction.x) / denominator
    return distance if distance > 0 and 0 <= along_edge <= 1 else None


def _ray_distance(contour: Sequence[Point], origin: Point, angle: float) -> float:
    direction = Point(math.cos(angle), math.sin(angle))
    hits = (_ray_hit(start, end, origin, direction) for start, end in itertools.pairwise(contour))
    return min(hit for hit in hits if hit is not None)


def _dot_centre(font: TTFont) -> Point:
    flattener = ContourFlattener()
    font.getGlyphSet()[_glyph_name(font, "O")].draw(flattener)
    pivot = Point(CORNER_PIVOT_X, CORNER_PIVOT_Y)
    distances = [_ray_distance(contour, pivot, DOT_ANGLE) for contour in flattener.contours]
    stroke_middle = (max(distances) + min(distances)) / 2
    return Point(
        pivot.x + stroke_middle * math.cos(DOT_ANGLE),
        BASELINE - (pivot.y + stroke_middle * math.sin(DOT_ANGLE)),
    )


def _corner_notch() -> pathops.Path:
    left = CORNER_PIVOT_X + CORNER_CUT
    bottom = BASELINE - (CORNER_PIVOT_Y + CORNER_CUT)
    notch = pathops.Path()
    notch.moveTo(left, bottom)
    notch.lineTo(FAR, bottom)
    notch.lineTo(FAR, -FAR)
    notch.lineTo(left, -FAR)
    notch.close()
    return notch


def build_outlines(font: TTFont) -> LogoOutlines:
    """Cut the O's corner and set the rest of the word after it."""
    hmtx = font["hmtx"]
    ring = pathops.op(_glyph_outline(font, WORD[0], 0), _corner_notch(), pathops.PathOp.DIFFERENCE)
    letters = pathops.Path()
    x_offset = hmtx[_glyph_name(font, WORD[0])][0]
    for char in WORD[1:]:
        letters = pathops.op(letters, _glyph_outline(font, char, x_offset), pathops.PathOp.UNION)
        x_offset += hmtx[_glyph_name(font, char)][0]
    return LogoOutlines(ring=ring, letters=letters, dot_centre=_dot_centre(font))


def _path_data(path: pathops.Path) -> str:
    pen = SVGPathPen(None, ntos=_number)
    path.draw(pen)
    return pen.getCommands()


def _svg(view_box: ViewBox, height: int, body: Sequence[str]) -> str:
    width = round(height * view_box.width / view_box.height)
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" width="{width}" height="{height}" '
        'role="img" aria-label="Odys">',
        NOTICE,
        "<title>Odys</title>",
        *body,
        "</svg>",
    ]
    return "\n".join(lines) + "\n"


def _dot(outlines: LogoOutlines, colour: str, radius: float = DOT_RADIUS) -> str:
    centre = outlines.dot_centre
    return f'<circle fill="{colour}" cx="{_number(centre.x)}" cy="{_number(centre.y)}" r="{_number(radius)}"/>'


def render_wordmark(outlines: LogoOutlines, palette: Palette) -> str:
    """The whole word."""
    bounds = pathops.op(outlines.ring, outlines.letters, pathops.PathOp.UNION).bounds
    body = [
        f'<path fill="{palette.letters}" d="{_path_data(outlines.ring)}"/>',
        _dot(outlines, palette.dot),
        f'<path fill="{palette.letters}" d="{_path_data(outlines.letters)}"/>',
    ]
    return _svg(ViewBox.around(bounds), WORDMARK_HEIGHT, body)


def render_mark(outlines: LogoOutlines, palette: Palette) -> str:
    """The O on its own."""
    body = [f'<path fill="{palette.letters}" d="{_path_data(outlines.ring)}"/>', _dot(outlines, palette.dot)]
    return _svg(ViewBox.around(outlines.ring.bounds), MARK_HEIGHT, body)


def render_favicon(outlines: LogoOutlines, palette: Palette) -> str:
    """The O on a transparent background, drawn heavier so it stays legible at 16 px."""
    x_min, y_min, x_max, y_max = outlines.ring.bounds
    side = max(x_max - x_min, y_max - y_min) * (1 + 2 * FAVICON_PADDING) + FAVICON_EMBOLDEN
    view_box = ViewBox((x_min + x_max - side) / 2, (y_min + y_max - side) / 2, side, side)
    body = [
        f'<path fill="{palette.letters}" stroke="{palette.letters}" stroke-width="{_number(FAVICON_EMBOLDEN)}" '
        f'stroke-linejoin="miter" d="{_path_data(outlines.ring)}"/>',
        _dot(outlines, palette.dot, DOT_RADIUS * FAVICON_DOT_SCALE),
    ]
    return _svg(view_box, FAVICON_SIZE, body)


def render_logo_assets() -> dict[str, str]:
    """Every logo SVG, by file name."""
    colours = json.loads(TOKENS_PATH.read_text())["color"]
    on_dark = Palette(letters=colours["text"], dot=colours["mint-400"])
    on_light = Palette(letters=colours["bg"], dot=colours["mint-700"])
    outlines = build_outlines(TTFont(FONT_PATH))
    return {
        "odys-wordmark-on-dark.svg": render_wordmark(outlines, on_dark),
        "odys-wordmark-on-light.svg": render_wordmark(outlines, on_light),
        "odys-mark-on-dark.svg": render_mark(outlines, on_dark),
        "odys-mark-on-light.svg": render_mark(outlines, on_light),
        "favicon-dark.svg": render_favicon(outlines, on_dark),
        "favicon-light.svg": render_favicon(outlines, on_light),
    }


def generate_logo() -> None:
    """Write every logo SVG to docs/assets/brand/."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, svg in render_logo_assets().items():
        path = OUTPUT_DIR / name
        path.write_text(svg)
        print(f"  ✓ {path.relative_to(REPOSITORY_ROOT)}")


if __name__ == "__main__":
    print("Generating logo...")
    generate_logo()
    print("Done!")
